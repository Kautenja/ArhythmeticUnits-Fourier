    rows = []
    for precision in ("float", "double"):
        rs = [r for r in audits if r["precision"] == precision]
        for r in rs:
            if r["expected_spectra"] != r["checked_spectra"] or r["expected_bins"] != r["checked_bins"]:
                raise ValueError("Incomplete stationary analysis coverage")
        values = [max(float(r[key]) for r in rs) for key in ("max_relative_l2", "max_relative_linf")]
        limit = 3e-4 if precision == "float" else 1e-10
        if max(values) > limit:
            raise ValueError("Analysis norm exceeds its frozen acceptance budget")
        count = sum(int(r["checked_spectra"]) for r in rs)
        diagnostic = sum(int(r["legacy_pointwise_failures"]) for r in rs)
        rows.append([precision, f"{count:,}", sci(values[0]), sci(values[1]), f"{diagnostic:,}"])
        macro(precision.title() + "Ltwo", sci(values[0])[1:-1])
        macro(precision.title() + "Linf", sci(values[1])[1:-1])
