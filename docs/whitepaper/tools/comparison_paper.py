def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify byte-for-byte regeneration without writing")
    args = parser.parse_args()
    files = generate()
    if args.check:
        for name, content in files.items():
            path = OUTPUT / name
            if not path.is_file() or path.read_bytes() != content.encode():
                raise SystemExit(f"Stale paper result asset: {path}")
        actual = {str(p.relative_to(OUTPUT)) for p in OUTPUT.rglob("*") if p.is_file()}
        if actual != set(files):
            raise SystemExit("Unexpected files in generated/paper-comparison")
        print(f"Verified {len(files)} editorial assets and all stationary hierarchical summaries")
    else:
        for name, content in files.items():
            path = OUTPUT / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        print(f"Wrote {len(files)} editorial assets to {OUTPUT}")


if __name__ == "__main__":
    main()
