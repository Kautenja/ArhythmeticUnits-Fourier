    index = e.read_json("index.json")
    expected_counts = dict(zip(GROUPS, (408, 719, 110, 46, 16)))
    for group in coverage["groups"]:
        name = group["group"]
        rows = e.data[name]["process-timings"]
        configs = {r["config_sha256"] for r in rows}
        macro(name.title().replace("-", "") + "Workloads", len(configs))
        if len(configs) != group["workloads"] or len(configs) != expected_counts[name]:
            raise ValueError("Campaign workload count mismatch")
